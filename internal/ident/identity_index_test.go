package ident

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"testing"

	"github.com/BeomSeogKim/crosshall/internal/hook/manifests"
)

var updateIndex = flag.Bool("update-index", false, "rewrite identity_index.go from the hook manifests")

// identity_index.go is the hook manifests' identity declarations, in setup
// order (the order an ambiguity error names the variables in).
func TestIdentityIndexMatchesManifests(t *testing.T) {
	want := renderIdentityIndex(t)
	if *updateIndex {
		if err := os.WriteFile("identity_index.go", want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile("identity_index.go")
	if err != nil || !bytes.Equal(got, want) {
		t.Fatalf("identity_index.go differs from the hook manifests (%v); run go generate ./internal/ident", err)
	}
}

func renderIdentityIndex(t *testing.T) []byte {
	t.Helper()
	var b bytes.Buffer
	b.WriteString("// Code generated by TestIdentityIndexMatchesManifests from internal/hook/manifests; DO NOT EDIT.\n\npackage ident\n\nvar identityIndex = []identityRow{\n")
	for _, adapter := range manifests.SetupOrder() {
		raw, err := manifests.Read(adapter)
		if err != nil {
			t.Fatal(err)
		}
		var m struct {
			Adapter     string `json:"adapter"`
			DisplayName string `json:"display_name"`
			CLIName     string `json:"cli_name"`
			SessionEnv  string `json:"session_env"`
			Identity    struct {
				Evidence     string   `json:"evidence"`
				VerifiedOn   []string `json:"verified_on"`
				AgentMarkers []string `json:"agent_markers"`
				Version      struct {
					Env          string `json:"env"`
					Prefix       string `json:"prefix"`
					Until        string `json:"until"`
					DashesToDots bool   `json:"dashes_to_dots"`
					Indirect     string `json:"indirect"`
					IndirectName string `json:"indirect_name"`
				} `json:"version"`
			} `json:"identity"`
		}
		if err := json.Unmarshal(raw, &m); err != nil {
			t.Fatal(err)
		}
		id, v := m.Identity, m.Identity.Version
		if m.SessionEnv == "" || id.Evidence == "" || v.Env == "" || (v.Indirect == "") != (v.IndirectName == "") {
			t.Fatalf("%s: incomplete identity declaration", adapter)
		}
		if m.CLIName == "" {
			m.CLIName = m.DisplayName
		}
		fmt.Fprintf(&b, "{adapter: %q, sessionEnv: %q, evidence: %q, verifiedOn: %#v, markers: %#v, cliName: %q,\n",
			m.Adapter, m.SessionEnv, id.Evidence, id.VerifiedOn, id.AgentMarkers, m.CLIName)
		fmt.Fprintf(&b, "version: versionSource{env: %q, prefix: %q, until: %q, dashesToDots: %t, indirect: %q, indirectName: %q}},\n",
			v.Env, v.Prefix, v.Until, v.DashesToDots, v.Indirect, v.IndirectName)
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	return out
}
