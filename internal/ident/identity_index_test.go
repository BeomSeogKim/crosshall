var updateIndex = flag.Bool("update-index", false, "rewrite identity_index.go from the hook manifests")

// identity_index.go is the shipped hook manifests' identity declarations,
// in setup order (the order an ambiguity error names the variables in).
func TestIdentityIndexMatchesManifests(t *testing.T) {
	want := renderIdentityIndex(t)
	if *updateIndex {
		if err := os.WriteFile("identity_index.go", want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile("identity_index.go")
	if err != nil || !bytes.Equal(got, want) {
		t.Fatalf("identity_index.go differs from the hook manifests (%v); run go generate ./internal/ident", err)
	}
}

// The index this build compiles holds every manifest's identity, in setup
// order: an adapter bundle built in under a tag adds its row from a file
// only that tag compiles.
func TestIdentityIndexCoversEveryManifest(t *testing.T) {
	var want []identityRow
	for _, adapter := range manifests.SetupOrder() {
		want = append(want, manifestIdentity(t, adapter))
	}
	if !reflect.DeepEqual(identityIndex, want) {
		t.Fatalf("identity index:\n%+v\nmanifests:\n%+v", identityIndex, want)
	}
}

// shipped reports whether this build ships adapter's manifest, rather than
// a bundle built in under a tag.
func shipped(adapter string) bool {
	_, err := fs.Stat(manifests.FS, adapter+".json")
	return err == nil
}

func manifestIdentity(t *testing.T, adapter string) identityRow {
	t.Helper()
	raw, err := manifests.Read(adapter)
	if err != nil {
		t.Fatal(err)
	}
	var m struct {
		Adapter     string `json:"adapter"`
		DisplayName string `json:"display_name"`
		CLIName     string `json:"cli_name"`
		SessionEnv  string `json:"session_env"`
		Identity    struct {
			Evidence     string   `json:"evidence"`
			VerifiedOn   []string `json:"verified_on"`
			AgentMarkers []string `json:"agent_markers"`
			Version      struct {
				Env          string `json:"env"`
				Prefix       string `json:"prefix"`
				Until        string `json:"until"`
				DashesToDots bool   `json:"dashes_to_dots"`
				Indirect     string `json:"indirect"`
				IndirectName string `json:"indirect_name"`
			} `json:"version"`
		} `json:"identity"`
	}
	if err := json.Unmarshal(raw, &m); err != nil {
		t.Fatal(err)
	}
	id, v := m.Identity, m.Identity.Version
	// A vendor may name no version: its sessions record "unknown".
	noVersion := v.Env == "" && (v.Prefix != "" || v.Until != "" || v.DashesToDots || v.Indirect != "")
	if m.SessionEnv == "" || id.Evidence == "" || noVersion || (v.Indirect == "") != (v.IndirectName == "") {
		t.Fatalf("%s: incomplete identity declaration", adapter)
	}
	if m.CLIName == "" {
		m.CLIName = m.DisplayName
	}
	return identityRow{adapter: m.Adapter, sessionEnv: m.SessionEnv, evidence: id.Evidence, verifiedOn: id.VerifiedOn,
		markers: id.AgentMarkers, cliName: m.CLIName,
		version: versionSource{env: v.Env, prefix: v.Prefix, until: v.Until, dashesToDots: v.DashesToDots, indirect: v.Indirect, indirectName: v.IndirectName}}
}

func renderIdentityIndex(t *testing.T) []byte {
	t.Helper()
	var b bytes.Buffer
	b.WriteString("// Code generated by TestIdentityIndexMatchesManifests from internal/hook/manifests; DO NOT EDIT.\n\npackage ident\n\nvar identityIndex = []identityRow{\n")
	for _, adapter := range manifests.SetupOrder() {
		if !shipped(adapter) {
			continue
		}
		r := manifestIdentity(t, adapter)
		v := r.version
		fmt.Fprintf(&b, "{adapter: %q, sessionEnv: %q, evidence: %q, verifiedOn: %#v, markers: %#v, cliName: %q,\n",
			r.adapter, r.sessionEnv, r.evidence, r.verifiedOn, r.markers, r.cliName)
		fmt.Fprintf(&b, "version: versionSource{env: %q, prefix: %q, until: %q, dashesToDots: %t, indirect: %q, indirectName: %q}},\n",
			v.env, v.prefix, v.until, v.dashesToDots, v.indirect, v.indirectName)
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	return out
}

// A manifest may declare no version source (a vendor that names no version
// in its sessions' environment, as a new adapter may at first). The index
// still renders, and such a session's version is "unknown".
func TestAnIdentityWithoutAVersionSource(t *testing.T) {
	shipped := map[string][]byte{}
	for _, adapter := range manifests.Names() {
		raw, err := manifests.Read(adapter)
		if err != nil {
			t.Fatal(err)
		}
		shipped[adapter] = raw
	}
	var codex map[string]any
	if err := json.Unmarshal(shipped["codex"], &codex); err != nil {
		t.Fatal(err)
	}
	delete(codex["identity"].(map[string]any), "version")
	edited, err := json.Marshal(codex)
	if err != nil {
		t.Fatal(err)
	}
	shipped["codex"] = edited
	restore := manifests.SwapReader(func(adapter string) ([]byte, error) { return shipped[adapter], nil })
	defer restore()
	if index := renderIdentityIndex(t); !bytes.Contains(index, []byte(`{adapter: "codex", sessionEnv: "CODEX_THREAD_ID"`)) ||
		!bytes.Contains(index, []byte(`version: versionSource{env: "", prefix: "", until: "", dashesToDots: false, indirect: "", indirectName: ""}`)) {
		t.Fatalf("index without codex's version source:\n%s", index)
	}

	saved := identityIndex
	defer func() { identityIndex = saved }()
	identityIndex = slices.Clone(saved)
	for i := range identityIndex {
		if identityIndex[i].adapter == "codex" {
			identityIndex[i].version = versionSource{}
		}
	}
	lookup := func(k string) (string, bool) {
		return map[string]string{"CODEX_THREAD_ID": "t", "CODEX_VERSION": "0.170.0"}[k], k == "CODEX_THREAD_ID" || k == "CODEX_VERSION"
	}
	id, err := ResolveEnvironment(lookup)
	if err != nil || id.Vendor != "codex" || id.Version != "unknown" || id.UnknownCLI() ||
		id.Warning() != "identity variable unverified on codex unknown" {
		t.Fatalf("%+v %q %v", id, id.Warning(), err)
	}
}
